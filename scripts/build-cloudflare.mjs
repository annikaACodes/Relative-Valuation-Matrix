import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "cloudflare-dist");

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });

for (const [source, destination] of [
  ["index.html", "index.html"],
  ["dashboard", "dashboard"],
  ["docs", "docs"],
  ["data/semiconductor_universe.csv", "data/semiconductor_universe.csv"],
  ["data/calendarized_metrics.csv", "data/calendarized_metrics.csv"],
  ["cloudflare/public", "."]
]) {
  const sourcePath = resolve(root, source);
  const destinationPath = resolve(output, destination);
  await mkdir(dirname(destinationPath), { recursive: true });
  await cp(sourcePath, destinationPath, { recursive: true });
}

const authSource = (await readFile(resolve(root, "cloudflare/worker/auth.js"), "utf8"))
  .replace(/^export\s+/gmu, "");
const workerSource = (await readFile(resolve(root, "cloudflare/worker/index.js"), "utf8"))
  .replace(/^import\s*\{[\s\S]*?\}\s*from\s*"\.\/auth\.js";\s*/u, "")
  .replace(/^export\s*\{\s*handleRequest,\s*secured\s*\};?\s*$/gmu, "");

const bundle = [
  "// Generated by scripts/build-cloudflare.mjs. Edit cloudflare/worker instead.",
  authSource.trim(),
  workerSource.trim(),
  ""
].join("\n\n");

await writeFile(resolve(output, "_worker.js"), bundle, "utf8");
console.log("Built cloudflare-dist with private Worker authentication.");
